import nextCoreWebVitals from 'eslint-config-next/core-web-vitals';
import nextTypescript from 'eslint-config-next/typescript';

// eslint-config-next 16 ships NATIVE flat configs (`eslint-config-next/
// core-web-vitals` and `/typescript` are arrays of flat config objects), so the
// `FlatCompat` shim this file used on v15 is gone. Keeping it was not merely
// redundant: loading a v16 config through eslintrc compat throws
// "Converting circular structure to JSON" before a single file is linted.
// `@eslint/eslintrc` is no longer a dependency of this package.

const eslintConfig = [
  {
    // Build output and Next's own generated ambient types. `next-env.d.ts` is
    // regenerated by every `next build`, is gitignored, and its triple-slash
    // reference is the shape Next writes — linting it produced a permanent
    // error nobody could fix, which is why `npm run lint` was not in CI.
    ignores: ['.next/**', '.next-mirror/**', '.next-release-*/**', 'node_modules/**', 'next-env.d.ts', 'playwright-report/**', 'test-results/**'],
  },
  ...nextCoreWebVitals,
  ...nextTypescript,
  {
    // Scoped to the same glob eslint-config-next 16 registers its plugins
    // under. In flat config a plugin namespace is only visible to config
    // objects that match the SAME file, and next's config object declares
    // `files: ['**/*.{js,jsx,mjs,ts,tsx,mts,cts}']` — note no .cjs. An
    // unscoped block naming a jsx-a11y rule therefore fails outright on
    // scripts/start-standalone.cjs with "could not find plugin".
    files: ['**/*.{js,jsx,mjs,ts,tsx,mts,cts}'],
    rules: {
      // A clickable <div> with no keyboard path recurred three times across
      // this platform's frontends (SSO's mobile-nav backdrop, GMS's guest
      // rows, DMS's hierarchy browser) before being caught — catch it in
      // review instead of a fourth time. `warn`, not `error`: this repo may
      // already have other click-handler divs that predate this rule: don't
      // let this newly-added rule fail an unrelated build.
      'jsx-a11y/click-events-have-key-events': 'warn',
      'jsx-a11y/no-static-element-interactions': 'warn',
    },
  },
  {
    // Node-side CommonJS: the standalone launcher and PostCSS/Tailwind config.
    // These run under Node before any bundler exists, so `require()` and an
    // anonymous default export are the correct forms, not lint debt.
    files: ['**/*.cjs', 'postcss.config.js'],
    rules: {
      '@typescript-eslint/no-require-imports': 'off',
      'import/no-anonymous-default-export': 'off',
    },
  },
];

export default eslintConfig;
